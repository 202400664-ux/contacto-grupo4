import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import rateLimit from 'express-rate-limit';
import { config } from './config';
import { authRouter } from './routes/auth';
import { contactsRouter } from './routes/contacts';
import { adminRouter } from './routes/admin';
import { errorHandler,notFound } from './middleware/errors';
export const app=express();app.disable('x-powered-by');app.use(helmet());app.use(cors({origin:config.corsOrigin,credentials:true}));app.use(express.json({limit:'32kb'}));app.use(cookieParser());
app.get('/api/health',(_req,res)=>res.json({status:'ok'}));app.use('/api/auth',rateLimit({windowMs:15*60*1000,limit:30,standardHeaders:true,legacyHeaders:false}),authRouter);app.use('/api/contacts',contactsRouter);app.use('/api/admin',adminRouter);app.use(notFound);app.use(errorHandler);